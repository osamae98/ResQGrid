const dict: Record<Locale, Record<string, string>> = { en: {}, ar };

// For helpers outside components (formatReason, timeline labels, map tooltips). Only call it while
// rendering a component that also uses useT(): that subscription is what re-renders it on a switch.
let current: Locale = "en";
export const tx = (s: string) => dict[current][s] ?? s;

interface I18n {
  locale: Locale;
  dir: "ltr" | "rtl";
  setLocale: (l: Locale) => void;
  t: (s: string) => string;
}

const Ctx = createContext<I18n>({ locale: "en", dir: "ltr", setLocale: () => {}, t: (s) => s });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("rq.locale") as Locale | null;
      if (saved === "ar" || saved === "en") setLocaleState(saved);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem("rq.locale", l);
    } catch {}
  }, []);

  setFormatLocale(locale);
  current = locale;
  const value = useMemo<I18n>(
    () => ({ locale, dir: locale === "ar" ? "rtl" : "ltr", setLocale, t: (s) => dict[locale][s] ?? s }),
    [locale, setLocale],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
export const useT = () => useContext(Ctx).t;
